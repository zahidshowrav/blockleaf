/**
 * Writes `packages/editor/src/core/emoji/data.ts`, the emoji the `:` picker
 * offers (`PA-03`).
 *
 * Run with `pnpm generate:emoji` after bumping either source. The output is
 * committed: it is data, the sources are dev dependencies only, and nobody
 * installing the editor downloads either.
 *
 * - Names and order from `unicode-emoji-json` (MIT, Mu-An Chiou).
 * - Search keywords from `emojilib` (MIT, Mu-An Chiou) — where `tada`, `+1`
 *   and `lol` come from.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const editor = join(root, 'packages/editor');
const require = createRequire(join(editor, 'package.json'));

/**
 * Emoji 14.0 (2021) and older. Newer ones draw as an empty box on systems
 * still in wide use, and a picker should not offer what the reader cannot
 * see. A host that wants them passes its own `items`.
 */
const MAX_EMOJI_VERSION = 14;

/** Enough to find an emoji by what it is for, without carrying every synonym. */
const MAX_KEYWORDS = 10;

interface UnicodeEmoji {
	name: string;
	emoji_version: string;
}

const readJson = <T>(specifier: string): T =>
	JSON.parse(readFileSync(require.resolve(specifier), 'utf8')) as T;

const names = readJson<Record<string, UnicodeEmoji>>(
	'unicode-emoji-json/data-by-emoji.json'
);
const keywords = readJson<Record<string, string[]>>(
	'emojilib/dist/emoji-en-US.json'
);
const version = (name: string): string =>
	readJson<{ version: string }>(`${name}/package.json`).version;

/** The package's own licence text, which MIT asks to travel with its data. */
const licence = (name: string): string =>
	readFileSync(
		join(dirname(require.resolve(`${name}/package.json`)), 'LICENSE'),
		'utf8'
	)
		.trim()
		.split('\n')
		.map((line) => ` * ${line}`.trimEnd())
		.join('\n');

/** No tab or newline can appear in a field, since those separate them. */
const clean = (value: string): string =>
	value.toLowerCase().replace(/\s+/g, ' ').trim();

const rows: string[] = [];
for (const [emoji, entry] of Object.entries(names)) {
	if (Number.parseFloat(entry.emoji_version) > MAX_EMOJI_VERSION) continue;
	const name = clean(entry.name);
	const inName = new Set(name.split(' '));
	const words = (keywords[emoji] ?? [])
		// The first keyword is the name with underscores.
		.slice(1)
		.map(clean)
		.filter((word) => word && !inName.has(word));
	const unique = [...new Set(words)].slice(0, MAX_KEYWORDS);
	rows.push([emoji, name, unique.join(' ')].join('\t'));
}

const output = `/*!
 * @license
 * unicode-emoji-json ${version('unicode-emoji-json')}:
 *
${licence('unicode-emoji-json')}
 *
 * emojilib ${version('emojilib')}:
 *
${licence('emojilib')}
 */

/**
 * Generated by \`scripts/generate-emoji-data.ts\`. Do not edit by hand.
 *
 * ${rows.length} emoji, Emoji ${MAX_EMOJI_VERSION}.0 and older, one per line:
 * the emoji, its name, then search keywords, separated by tabs. Names and
 * order from unicode-emoji-json ${version('unicode-emoji-json')}, keywords
 * from emojilib ${version('emojilib')}; both MIT, by Mu-An Chiou.
 *
 * One string rather than an array of objects: it is the smallest form to
 * ship and to parse, and it is only parsed when the picker first opens.
 */
export const EMOJI_DATA = ${JSON.stringify(rows.join('\n'))};
`;

writeFileSync(join(editor, 'src/core/emoji/data.ts'), output);
console.log(`[blockleaf] wrote ${rows.length} emoji`);
